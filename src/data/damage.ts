const BUCKET = "dsp-dvic-photos";
const MODEL = "damage-clip-v1";

function photo(
  id: string,
  eventId: string,
  dvicId: string,
  vehicleId: string,
  zone: DamagePhoto["zone"],
  capturedAt: string,
  driverId: string,
  angle: DamagePhoto["camera_angle"],
  baseline: boolean,
  extra: Partial<DamagePhoto> = {},
): DamagePhoto {
  const date = capturedAt.slice(0, 10);
  return {
    id,
    damage_event_id: eventId,
    dvic_id: dvicId,
    vehicle_id: vehicleId,
    zone,
    captured_at: capturedAt,
    captured_by_driver_id: driverId,
    storage_bucket: BUCKET,
    storage_path: `vehicles/${vehicleId}/${date}/${zone}-${id}.jpg`,
    content_type: "image/jpeg",
    content_hash: `sha256:${id}-${vehicleId}-${zone}`,
    width_px: 1600,
    height_px: 1200,
    camera_angle: angle,
    is_baseline: baseline,
    embedding_status: extra.embedding_status ?? (baseline ? "ready" : "ready"),
    embedding_model: extra.embedding_model ?? MODEL,
    embedding_dims: 768,
    embedding_ref: extra.embedding_ref ?? `vec://${BUCKET}/${id}`,
    compared_to_photo_id: extra.compared_to_photo_id ?? null,
    similarity_score: extra.similarity_score ?? null,
    change_confidence: extra.change_confidence ?? null,
    ai_notes: extra.ai_notes ?? null,
  };
}

