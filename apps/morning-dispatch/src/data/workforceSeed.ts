const onboardCourses = [
  "DSP New Hire Orientation",
  "Mentor / FICO",
  "DVIC / Pre-trip",
  "Nursery Route",
  "Drug Screen & Background",
  "Uniform & Badge",
] as const;

function onboard(
  idPrefix: string,
  driverId: string,
  recruitingId: string,
  statuses: Array<TrainingRecord["status"]>,
  startOffset: number,
): TrainingRecord[] {
  return onboardCourses.map((course, index) => {
    const status = statuses[index];
    const started = status === "not_started" ? null : addDays(TODAY, startOffset + index);
    const completed = status === "completed" ? addDays(TODAY, startOffset + index + 1) : null;
    return {
      id: `${idPrefix}-${index + 1}`,
      driver_id: driverId,
      recruiting_id: recruitingId,
      course,
      category: "onboarding" as const,
      status,
      started_at: started,
      completed_at: completed,
      due_date: addDays(TODAY, 10 - index),
      score: status === "completed" ? 90 + index : null,
      required: true,
    };
  });
}

