function offboard(
  idPrefix: string,
  driverId: string,
  statuses: Array<TrainingRecord["status"]>,
  completedOffset: number,
): TrainingRecord[] {
  return offboardCourses.map((course, index) => {
    const status = statuses[index];
    return {
      id: `${idPrefix}-${index + 1}`,
      driver_id: driverId,
      recruiting_id: idPrefix.startsWith("trn-elena") ? "rec-12" : null,
      course,
      category: "offboarding" as const,
      status,
      started_at: status === "not_started" ? null : addDays(TODAY, completedOffset),
      completed_at: status === "completed" ? addDays(TODAY, completedOffset + index) : null,
      due_date: addDays(TODAY, 3),
      score: null,
      required: true,
    };
  });
}

